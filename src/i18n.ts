const dicts: Record<Lang, Record<I18nKey, string>> = { ja, en, es, zh, fr, de, pt, ko };

let current: Lang = 'ja';

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: I18nKey): string {
  return dicts[current][key];
}

/** Sorted key list for a language — used by the parity test. */
export function dictionaryKeys(lang: Lang): string[] {
  return Object.keys(dicts[lang]).sort();
}

export function detectLang(saved: string | null): Lang {
  if (saved !== null && (LANGS as readonly string[]).includes(saved)) return saved as Lang;
  const prefix = navigator.language.toLowerCase().split('-')[0];
  if ((LANGS as readonly string[]).includes(prefix)) return prefix as Lang;
  return 'en';
}
